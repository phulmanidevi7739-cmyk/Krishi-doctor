    fun confidenceLabelText(level: ConfidenceLevel): String = when (level) {
        ConfidenceLevel.LOW -> if (isHindi) "कम संभावना (Low)" else "Low Confidence"
        ConfidenceLevel.MODERATE -> if (isHindi) "मध्यम संभावना (Moderate)" else "Moderate Confidence"
        ConfidenceLevel.HIGH -> if (isHindi) "अच्छी संभावना (सतर्क अनुमान)" else "Higher Confidence (Estimate)"
    }

    fun healthLabelText(status: HealthStatus): String = when (status) {
        HealthStatus.HEALTHY -> healthyStatusLabel
        HealthStatus.DISEASED -> diseasedStatusLabel
        HealthStatus.UNCERTAIN -> uncertainStatusLabel
    }

    fun weatherConditionText(group: WeatherConditionGroup): String = when (group) {
        WeatherConditionGroup.CLEAR -> if (isHindi) "साफ मौसम" else "Clear Sky"
        WeatherConditionGroup.PARTLY_CLOUDY -> if (isHindi) "हल्के बादल" else "Partly Cloudy"
        WeatherConditionGroup.CLOUDY -> if (isHindi) "बादल छाए हैं" else "Cloudy"
        WeatherConditionGroup.FOG -> if (isHindi) "कोहरा / धुंध" else "Fog / Mist"
        WeatherConditionGroup.RAIN -> if (isHindi) "बारिश / फुहार" else "Rain / Drizzle"
        WeatherConditionGroup.THUNDERSTORM -> if (isHindi) "गरज के साथ बारिश" else "Thunderstorm"
    }

    fun pestRiskTitle(level: PestDiseaseRiskLevel): String = when (level) {
        PestDiseaseRiskLevel.HIGH_HUMIDITY_FUNGAL ->
            if (isHindi) "रोग जोखिम: नमी से फफूँद का खतरा" else "Disease Watch: High Humidity Fungal Risk"
        PestDiseaseRiskLevel.HOT_DRY_PEST ->
            if (isHindi) "कीट जोखिम: गर्मी में रसचूसक कीट" else "Pest Watch: Hot & Dry Sap-Pest Risk"
        PestDiseaseRiskLevel.COOL_DAMP_MILDEW ->
            if (isHindi) "रोग जोखिम: ठंड व ओस से झुलसा/बुकनी" else "Disease Watch: Cool & Damp Blight Risk"
        PestDiseaseRiskLevel.MODERATE_NORMAL ->
            if (isHindi) "मौसम संतुलित (सामान्य निगरानी)" else "Balanced Weather (Routine Check)"
    }

    fun pestRiskAdvice(level: PestDiseaseRiskLevel): String = when (level) {
        PestDiseaseRiskLevel.HIGH_HUMIDITY_FUNGAL ->
            if (isHindi) {
                "अधिक नमी से पत्तियों पर झुलसा (Blight), रतुआ और फफूँद रोग तेजी से बढ़ सकते हैं। अतिरिक्त सिंचाई टालें और पत्तियों की जांच करें।"
            } else {
                "High humidity favors fungal blights, rust, and leaf spots. Avoid over-irrigation and inspect leaf undersides."
            }
        PestDiseaseRiskLevel.HOT_DRY_PEST ->
            if (isHindi) {
                "तेज गर्मी व कम नमी में सफेद मक्खी, माहू और मकड़ी (Mites) जैसे रसचूसक कीट बढ़ सकते हैं। खेत में नमी बनाए रखें।"
            } else {
                "Hot, dry air increases whitefly, thrips, and spider mite pressure. Watch for leaf curling and maintain soil moisture."
            }
        PestDiseaseRiskLevel.COOL_DAMP_MILDEW ->
            if (isHindi) {
                "ठंडा व नमी भरा मौसम बुकनी रोग (Powdery Mildew) और अगेती/पछेती झुलसा बढ़ा सकता है। सुबह पत्तियों के धब्बे देखें।"
            } else {
                "Cool, damp air can trigger powdery mildew and blight. Check leaves for white powder or water-soaked spots."
            }
        PestDiseaseRiskLevel.MODERATE_NORMAL ->
            if (isHindi) {
                "वर्तमान तापमान व नमी सामान्य है। फसल की नियमित निगरानी और साफ-सफाई जारी रखें।"
            } else {
                "Current temperature and humidity are moderate. Continue regular crop inspection and field hygiene."
            }
    }

    private val isHindi: Boolean
        get() = appTitle == "कृषि डॉक्टर"
}

